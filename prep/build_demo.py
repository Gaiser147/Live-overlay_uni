"""Baut die synthetische Demo-Vorlesung neu: PDF → Extraktion → Karten (handgeschrieben) → App.

Aufruf: python prep/build_demo.py
"""

import json
import shutil
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "prep"))

import extract  # noqa: E402
import make_deck  # noqa: E402
import make_demo_pdf  # noqa: E402

FIX = ROOT / "test" / "fixtures" / "demo"
OUT = ROOT / "app" / "public" / "decks" / "demo"


def embed_origin(png: Path, text: str) -> None:
    """Herkunft als PNG-tEXt-Chunk (Schlüssel wie bei `impeccable embed-prompt`), vor IEND."""
    data = png.read_bytes()
    body = b"impeccable:prompt\x00" + text.encode("latin-1", "replace")
    chunk = struct.pack(">I", len(body)) + b"tEXt" + body + struct.pack(">I", zlib.crc32(b"tEXt" + body) & 0xFFFFFFFF)
    iend = data.rindex(b"IEND") - 4
    png.write_bytes(data[:iend] + chunk + data[iend:])


def main() -> None:
    pdf = FIX / "demo-handout.pdf"
    make_demo_pdf.build(pdf)
    if OUT.exists():
        shutil.rmtree(OUT)
    extract.extract(pdf, OUT)
    make_deck.build(OUT, "demo", "2026-11-10", "heuristic", FIX / "cards.json", ROOT / "profile.md", 1)
    deck = json.loads((OUT / "deck.json").read_text(encoding="utf-8"))
    deck["title"] = "Lineare Abbildungen (Demo)"
    deck["synthetic"] = True
    deck["generated"]["by"] = "hand"
    (OUT / "deck.json").write_text(json.dumps(deck, ensure_ascii=False, indent=1), encoding="utf-8")
    for png in sorted((OUT / "slides").glob("*.png")):
        embed_origin(
            png,
            f"Origin: synthetic demo slide {png.stem} of 12, not a real lecture. Rendered from test/fixtures/demo/demo-handout.pdf "
            "(generated by prep/make_demo_pdf.py) with prep/extract.py (PyMuPDF, 250 dpi). Regenerate with: npm run demo:deck.",
        )
    (OUT / "pages.json").unlink()
    (OUT / "keyterms.json").unlink()
    shutil.copy(FIX / "transcript.txt", OUT / "transcript.txt")
    shutil.copy(OUT / "deck.json", FIX / "deck.json")
    print(f"Demo-Deck → {OUT}")


if __name__ == "__main__":
    main()
